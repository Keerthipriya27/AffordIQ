"""Run a complete, credential-free evaluation of a generated output CSV.

The evaluator only reads local CSV/JSON files. It never loads, prints, or
transmits API keys, prompts, or raw evidence.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time
from pathlib import Path
from typing import Dict, Mapping

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent))

from compare_samples import compare_predictions
from validate_output import read_csv, validate_rows


def _load_requests(path: Path) -> Dict[str, Mapping[str, str]]:
    if not path.exists():
        return {}
    _, rows = read_csv(path)
    return {row.get("request_id", ""): row for row in rows if row.get("request_id", "")}


def _number(value, default=0):
    try:
        return int(value)
    except (TypeError, ValueError):
        return default


def _usage(stats_path: Path, request_count: int) -> Dict[str, object]:
    """Normalize both current and legacy pipeline telemetry formats."""
    stats = {}
    if stats_path.exists():
        try:
            stats = json.loads(stats_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            stats = {}

    usage = stats.get("model_usage", stats.get("usage", {}))
    token_usage = stats.get("token_usage", {})
    input_tokens = _number(usage.get("input_tokens", token_usage.get("input_tokens", 0)))
    output_tokens = _number(usage.get("output_tokens", token_usage.get("output_tokens", 0)))
    calls = _number(usage.get("calls", usage.get("gemini_calls", stats.get("gemini_calls", 0))))
    total_cost = float(
        usage.get(
            "estimated_total_cost_usd",
            usage.get("estimated_cost_usd", stats.get("estimated_cost_usd", 0.0)),
        )
        or 0.0
    )
    count = max(1, request_count)
    return {
        "provider": usage.get("provider", os.getenv("MODEL_PROVIDER", "Google Gemini")),
        "model_name": usage.get("model_name", os.getenv("GEMINI_MODEL", "gemini-2.5-flash")),
        "calls": calls,
        "input_tokens": input_tokens,
        "output_tokens": output_tokens,
        "total_tokens": input_tokens + output_tokens,
        "average_tokens_per_request": round((input_tokens + output_tokens) / count, 2),
        "estimated_total_cost_usd": round(total_cost, 6),
        "estimated_cost_per_request_usd": round(total_cost / count, 6),
    }


def _failure_categories(validation: Mapping[str, object]) -> Dict[str, int]:
    return {
        "schema": int(not validation["schema_valid"]),
        "duplicate_request_id": len(validation["duplicate_request_ids"]),
        "missing_request_id": len(validation["missing_request_ids"]),
        "unexpected_request_id": len(validation["unexpected_request_ids"]),
        "blank_request_id": len(validation["blank_request_ids"]),
        "invalid_status": len(validation["invalid_statuses"]),
        "invalid_payment_method": len(validation["invalid_payment_methods"]),
        "malformed_plan": len(validation["malformed_plans"]),
        "arithmetic": len(validation["arithmetic_errors"]),
        "safe_amount": len(validation["safe_amount_errors"]),
        "safety": len(validation["safety_errors"]),
        "earliest_date": len(validation["earliest_date_errors"]),
        "spending_change": len(validation["spending_change_errors"]),
        "explanation_consistency": len(validation["explanation_errors"]),
    }


def _difficult_requests(validation: Mapping[str, object]):
    grouped = {}
    sources = (
        ("malformed_plan", validation["malformed_plans"]),
        ("safe_amount", [{"request_id": x, "errors": ["safe amount"]} for x in validation["safe_amount_errors"]]),
        ("earliest_date", [{"request_id": x, "errors": ["earliest date"]} for x in validation["earliest_date_errors"]]),
        ("spending_change", [{"request_id": x, "errors": ["spending change"]} for x in validation["spending_change_errors"]]),
        ("explanation", [{"request_id": x, "errors": ["explanation"]} for x in validation["explanation_errors"]]),
    )
    for category, entries in sources:
        for entry in entries:
            request_id = entry["request_id"]
            grouped.setdefault(request_id, []).extend(
                f"{category}: {error}" for error in entry.get("errors", [category])
            )
    return [
        {"request_id": request_id, "reasons": reasons}
        for request_id, reasons in sorted(grouped.items())
    ]


def _write_usage_report(path: Path, usage: Mapping[str, object]) -> None:
    path.write_text(
        "# Model Usage Report\n\n"
        "Generated by `evaluation/evaluate.py`. No API keys or credentials are recorded.\n\n"
        "| Metric | Value |\n| --- | --- |\n"
        f"| Model provider | {usage['provider']} |\n"
        f"| Model name | {usage['model_name']} |\n"
        f"| Number of calls | {usage['calls']} |\n"
        f"| Input tokens | {usage['input_tokens']} |\n"
        f"| Output tokens | {usage['output_tokens']} |\n"
        f"| Total tokens | {usage['total_tokens']} |\n"
        f"| Average tokens/request | {usage['average_tokens_per_request']} |\n"
        f"| Estimated total cost | ${usage['estimated_total_cost_usd']:.6f} |\n"
        f"| Estimated cost/request | ${usage['estimated_cost_per_request_usd']:.6f} |\n",
        encoding="utf-8",
    )


def evaluate(
    output_path: Path,
    requests_path: Path,
    expected_path: Path,
    stats_path: Path,
    report_path: Path,
    metrics_path: Path,
    usage_report_path: Path,
) -> Dict[str, object]:
    started = time.perf_counter()
    headers, predictions = read_csv(output_path)
    requests = _load_requests(requests_path)
    validation = validate_rows(headers, predictions, requests)
    expected = read_csv(expected_path)[1] if expected_path.exists() else []
    comparison = compare_predictions(predictions, expected)
    failures = _failure_categories(validation)
    difficult = _difficult_requests(validation)
    request_count = len(requests) or len(predictions)
    usage = _usage(stats_path, request_count)

    metrics = {
        "evaluation_runtime_seconds": round(time.perf_counter() - started, 4),
        "total_requests": request_count,
        "rows_evaluated": len(predictions),
        "status_accuracy": comparison["status_accuracy"],
        "payment_method_accuracy": comparison["payment_method_accuracy"],
        "payment_plan_validity": round(1 - failures["malformed_plan"] / max(1, len(predictions)), 4),
        "safe_amount_mean_absolute_error": comparison["safe_amount_mean_absolute_error"],
        "earliest_date_accuracy": comparison["earliest_date_accuracy"],
        "spending_change_validity": round(1 - failures["spending_change"] / max(1, len(predictions)), 4),
        "explanation_consistency": round(1 - failures["explanation_consistency"] / max(1, len(predictions)), 4),
        "failure_categories": failures,
        "difficult_requests": difficult,
        "validation": validation,
        "sample_comparison": comparison,
        "model_usage": usage,
    }
    metrics_path.parent.mkdir(parents=True, exist_ok=True)
    metrics_path.write_text(json.dumps(metrics, indent=2), encoding="utf-8")
    usage_report_path.parent.mkdir(parents=True, exist_ok=True)
    _write_usage_report(usage_report_path, usage)

    report = [
        "# Evaluation Report", "",
        f"- Requests: {request_count}",
        f"- Rows evaluated: {len(predictions)}",
        f"- Status accuracy: {comparison['status_accuracy']}",
        f"- Payment method accuracy: {comparison['payment_method_accuracy']}",
        f"- Payment-plan validity: {metrics['payment_plan_validity']:.2%}",
        f"- Safe amount MAE: {comparison['safe_amount_mean_absolute_error']}",
        f"- Earliest-date accuracy: {comparison['earliest_date_accuracy']}",
        f"- Spending-change validity: {metrics['spending_change_validity']:.2%}",
        f"- Explanation consistency: {metrics['explanation_consistency']:.2%}",
        f"- Difficult requests: {len(difficult)}", "",
        "## Failure Categories", "",
    ]
    report.extend(f"- {name}: {count}" for name, count in failures.items())
    report.extend(["", "## Model Usage", "", json.dumps(usage, indent=2)])
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text("\n".join(report) + "\n", encoding="utf-8")
    return metrics


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=root / "output.csv")
    parser.add_argument("--requests", type=Path, default=root / "dataset" / "prediction_requests.csv")
    parser.add_argument("--expected", type=Path, default=root / "dataset" / "sample_requests.csv")
    parser.add_argument("--stats", type=Path, default=root / "validation_statistics.json")
    parser.add_argument("--report", type=Path, default=root / "evaluation" / "evaluation_report.md")
    parser.add_argument("--metrics", type=Path, default=root / "evaluation" / "metrics.json")
    parser.add_argument("--usage-report", type=Path, default=root / "evaluation" / "usage_report.md")
    args = parser.parse_args()
    print(json.dumps(evaluate(
        args.output, args.requests, args.expected, args.stats,
        args.report, args.metrics, args.usage_report,
    ), indent=2))


if __name__ == "__main__":
    main()
